    private void agregarAsignatura(){
        
        
        int idGrado = cbmGrado.getSelectedIndex();
        String nuevaAsignatura = txtNuevaAsignatura.getText();
        if (nuevaAsignatura == null) {
            JOptionPane.showMessageDialog(this, "Debe Escribir el nombre de la nueva asignatura");
            return;
        }
        
        if (idGrado == 0 ) {
            JOptionPane.showMessageDialog(this, "Debe Asignarle un grado a la asignatura");
            return;
        }
        
        
        
       try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            PreparedStatement pstm = conexion.prepareCall("call sp_agregar_asignatura(?,?)");
            pstm.setString(1, nuevaAsignatura);
            pstm.setInt(2, idGrado);
            pstm.execute();
            limpiar();
            
        }catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error de la base de datos" + e);
        }
    }
    private void limpiar(){
        txtNuevaAsignatura.setText("");
    }
    private void mostrarAsignaturas(){
       try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            DefaultTableModel modelo = new DefaultTableModel();
            PreparedStatement pstm = conexion.prepareCall("call sp_listar_asignaturas()");
            ResultSet rs = pstm.executeQuery();
            ResultSetMetaData rsmt = rs.getMetaData();
            
            for(int i =1; i<= rsmt.getColumnCount(); i++){
                modelo.addColumn(rsmt.getColumnLabel(i));
            }
            while (rs.next()) {               
               int id = rs.getInt("Id");
               String nombreAsignatura = rs.getString("Nombre");
               Asignatura asignatura = new Asignatura(id,nombreAsignatura);
               listaAsignaturas.add(asignatura);
               modelo.addRow(new Object []{asignatura.getIdAsignatura(),asignatura.getNombre()});
           }
            tableAsignaturas.setModel(modelo);
            
            
        }catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error de la base de datos" + e);
        }    
    }
    private void llenarcombo(){
        try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            
            PreparedStatement pstm = conexion.prepareCall("call sp_combo_grados()");
            ResultSet rs = pstm.executeQuery();
            cbmGrado.removeAllItems();
            cbmGrado.addItem("Seleccione...");
            while (rs.next()) {     
                int id = rs.getInt("idGrado");
                String nombre = rs.getString("nombreGrado");
                Grado grado = new Grado(id,nombre);
                cbmGrado.addItem(grado.getNombre());
                listaGrados.add(grado);
            }
        }catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error de la base de datos" + e);
        }
    }

