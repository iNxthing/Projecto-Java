    private void agregarNuevoGrado(){
        String gradoNuevo = txtNuevoGrado.getText();
        if (gradoNuevo == null) {
            JOptionPane.showMessageDialog(this, "Debe Escribir el nombre de el nuevo Grado");
        }
        try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            
            PreparedStatement nuevoGrado = conexion.prepareCall("call sp_agregar_grado(?)");
            nuevoGrado.setString(1, gradoNuevo);
            nuevoGrado.execute();
            limpiar();
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error de la base de datos " + e);
        }
    }
    private void limpiar(){
        txtNuevoGrado.setText("");
    }
    private void mostrarGrados(){
        try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            DefaultTableModel modelo = new DefaultTableModel();
            
            PreparedStatement pstm = conexion.prepareCall("call sp_combo_grados()");
            
            ResultSet rs  = pstm.executeQuery();
            ResultSetMetaData rsmt = rs.getMetaData();
            
            for(int i =1; i<= rsmt.getColumnCount(); i++){
                modelo.addColumn(rsmt.getColumnLabel(i));
            }
            
            while (rs.next()) {                
                int id = rs.getInt("idGrado");
                String nombre = rs.getString("nombreGrado");
                Grado grado = new Grado(id,nombre);
                gradoList.add(grado);
                
                modelo.addRow(new Object[]{grado.getIdGrado(),grado.getNombre()});
            }
            tableGrados.setModel(modelo);
            
            

        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error de la base de datos " + e);
        }
    }

    
    

