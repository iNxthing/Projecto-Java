    private void mostrarInfo(){
        try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            DefaultTableModel modelo = new DefaultTableModel();
            
            PreparedStatement pstm = conexion.prepareCall("call sp_respaldo_de_estudiante()");
            ResultSet rs = pstm.executeQuery();
            
            ResultSetMetaData rsmt = rs.getMetaData();
            
            for(int i =1; i<= rsmt.getColumnCount(); i++){
                modelo.addColumn(rsmt.getColumnLabel(i));
            }
            while (rs.next()) {                
                modelo.addRow(new Object[]{rs.getInt("Id"),rs.getString("Documento"),rs.getString("Nombre"),rs.getString("Fecha Eliminacion")});
            }
            
            tableRespaldoEstudiante.setModel(modelo); 
            
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error de la base de datos " + e);
        }
    }

